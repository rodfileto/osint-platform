SELECT
    short_id(id)                                     AS id,
    lower(regexp_replace(doi, '^https?://(dx\.)?doi\.org/', '')) AS doi,
    regexp_extract(ids['pmid'], '(\d+)$')            AS pmid,
    regexp_extract(ids['pmcid'], '(PMC\d+)$')        AS pmcid,
    coalesce(title, display_name)                    AS title,
    publication_year,
    publication_date,
    type,
    language,
    is_retracted,
    is_paratext,
    is_xpac,
    abstract_inverted_index IS NOT NULL              AS has_abstract,
    authors_count,
    institutions_distinct_count,
    countries_distinct_count,
    referenced_works_count,
    cited_by_count,
    fwci,
    citation_normalized_percentile.value             AS citation_percentile,
    citation_normalized_percentile.is_in_top_1_percent  AS is_top_1_percent,
    citation_normalized_percentile.is_in_top_10_percent AS is_top_10_percent,
    short_id(primary_topic.id)                       AS topic_id,
    primary_topic.score                              AS topic_score,
    short_id(primary_topic.subfield.id)::INTEGER     AS subfield_id,
    short_id(primary_topic.field.id)::INTEGER        AS field_id,
    short_id(primary_topic.domain.id)::INTEGER       AS domain_id,
    short_id(primary_location.source.id)             AS source_id,
    primary_location.source.type                     AS source_type,
    primary_location.source.issn_l                   AS source_issn_l,
    primary_location.source.is_core                  AS source_is_core,
    biblio.volume,
    biblio.issue,
    biblio.first_page,
    biblio.last_page,
    open_access.is_oa                                AS is_oa,
    open_access.oa_status,
    created_date::DATE                               AS created_date,
    updated_date
FROM read_parquet('{src}')
ORDER BY id
